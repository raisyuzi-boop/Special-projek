const EAST = new Set(["Sabah", "Sarawak", "Labuan"])

export function quoteShipping(state, subtotal) {
  const east = EAST.has(state)
  const threshold = east ? EAST_FREE : FREE_SHIPPING
  const base = east ? 16 : 8
  const fee = subtotal <= 0 || subtotal >= threshold ? 0 : base
  return {
    fee,
    threshold,
    region: east ? "Sabah / Sarawak / Labuan" : "Semenanjung",
  }
}
